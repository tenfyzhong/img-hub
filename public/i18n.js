export function resolveLanguage(browserLanguages = [], savedLanguage = null) {
    if (savedLanguage === "en" || savedLanguage === "zh-CN") return savedLanguage;
    const preferred = Array.isArray(browserLanguages) ? browserLanguages[0] : browserLanguages;
    return String(preferred || "").toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(language, key, values = {}) {
    const catalog = translations[language] || translations.en;
    const template = catalog[key] ?? translations.en[key] ?? key;
    return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) => (
        Object.hasOwn(values, name) ? String(values[name]) : match
    ));
}
